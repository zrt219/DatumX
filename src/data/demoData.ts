const validatorDirectory = Object.fromEntries(validators.map((validator) => [validator.id, validator])) as Record<string, ValidatorRecord>

function review(
  validatorId: ValidatorRecord['id'],
  approved: boolean,
  confidence: number,
  reviewUri: string,
  submittedAt: string,
): ReviewRecord {
  const validator = validatorDirectory[validatorId]
  return {
    validatorId,
    validatorName: validator.name,
    approved,
    confidence,
    reviewUri,
    submittedAt,
    stake: validator.stake,
  }
}

function issue(
  id: string,
  title: string,
  severity: IssueRecord['severity'],
  owner: string,
  state: IssueRecord['state'],
  summary: string,
): IssueRecord {
  return { id, title, severity, owner, state, summary }
}

